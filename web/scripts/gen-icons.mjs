// Symbols icon the web app draws (DECISIONS.md D13, D16).
//
// The category icon keys come from /shared/category-style.json (the same
// keys the phone renders with Flutter's Icons.*); the rest are UI icons. Only
// these glyphs end up in the bundle: no icon font, no third-party request,
