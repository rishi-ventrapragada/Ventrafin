// Keys are Material Icons names (what the database stores and Flutter draws).
// Material Symbols renamed a few; these point at the equivalent glyph. On the
// phone card_giftcard and redeem are the same gift-card picture too.
const SYMBOLS_NAME = {
  smartphone: 'mobile',
  card_giftcard: 'redeem',
  auto_awesome: 'star_shine',
  expand_more: 'keyboard_arrow_down',
}

function pathsOf(key, fill) {
  const name = SYMBOLS_NAME[key] ?? key
  const file = join(pkgDir, 'outlined', `${name}${fill ? '-fill' : ''}.svg`)
  let svg
  try {
    svg = readFileSync(file, 'utf8')
  } catch {
    throw new Error(`Material Symbols has no "${name}"${fill ? ' (filled)' : ''} icon for "${key}": ${file}`)
  }
  if (!svg.includes('viewBox="0 -960 960 960"')) throw new Error(`Unexpected viewBox in ${file}`)
  const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
  if (d.length === 0) throw new Error(`No path in ${file}`)
  return d.join(' ')
}

function block(names, fill) {
  return [...new Set(names)]
    .sort()
    .map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(pathsOf(n, fill))},`)
    .join('\n')
}

const out = `// GENERATED by scripts/gen-icons.mjs from @material-symbols/svg-400@${pkgVersion}
// (Google Material Symbols, Apache-2.0). Do not edit by hand.
// Path data for a 960x960 viewBox with origin (0, -960).

/** Filled (FILL=1) glyphs: category icons and filled UI icons. */
export const FILLED_ICONS: Readonly<Record<string, string>> = {
${block(filled, true)}
}

/** Outlined (FILL=0) glyphs: UI icons. */
export const OUTLINED_ICONS: Readonly<Record<string, string>> = {
${block(outlined, false)}
}
`
